"""FREQ (b-log 21/11): how often a ghost window could be hit, estimated offline from windows we measured.

Measured windows (seconds), from data already collected:
  K-9   tap to server commit: ISSUED (written just before the tap) to GreenMail's 250, every LLM-agent episode with
        both stamps (artifact/results/real/agent*/episodes.csv).
  K-9   tap to on-screen success: Send to K-9's append into the Sent folder, acknowledged sends of campaign 2.
  Element tap to "Sent" indicator: upper end of the first dump that showed it, no-fault cell of campaign 2.
  Etar+DAVx5 save to server copy (hop 2): TN1 committed calibration labels, save tap to the proxy's commit barrier
        (testbed/runs/tn1-calibration/*/clock.json; exported here as a CSV).
The estimate is NOT a measurement: interruptions are assumed to arrive as a Poisson process of rate lam per hour
of agent activity, and a commit is a ghost if one lands inside its window, P = 1 - exp(-lam * w / 3600). For K-9 a
lost SMTP reply alone also makes a ghost, so a per-send lost-reply rate is listed beside it. The rates are a grid,
not values from the literature. Writes artifact/results/real/ghost_window/{windows.csv,estimate.csv,SUMMARY.md}."""
import csv
import glob
import json
import math
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REAL = ROOT / 'artifact/results/real'
OUT = REAL / 'ghost_window'
RATES = (0.1, 1.0, 10.0)           # interruptions per hour of agent activity (assumed grid)
LOST_REPLY = (1e-4, 1e-3, 1e-2)    # per-send lost-reply rate for K-9 (assumed grid)


def read(path):
    with open(path, encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def windows():
    w = {}
    k9 = []
    for arm in ('agent', 'agent_guarded', 'agent_rules', 'agent_t3a', 'agent_killagent'):
        for r in read(REAL / arm / 'episodes.csv'):
            if r['t_issue_utc'] and r['t_data_250_utc']:
                k9.append((int(r['t_data_250_utc']) - int(r['t_issue_utc'])) / 1e9)
    w['K-9, tap to server commit'] = k9
    w['K-9, tap to on-screen success (Sent append)'] = [
        float(r['sent_server_append_after_send_s']) for r in read(REAL / 'campaign2/c2_k9_sent_trials.csv')
        if r['timing'] == 'acked' and r['sent_server_append_after_send_s']]
    w['Element, tap to Sent indicator (dump upper end)'] = [
        float(r['sent_hi_s']) for r in read(REAL / 'campaign2/c2_element_trials.csv')
        if r['fault'] == 'none' and r['sent_hi_s']]
    hop2_csv = OUT / 'etar_hop2_windows.csv'
    clocks = sorted(glob.glob(str(ROOT / 'testbed/runs/tn1-calibration/c*/clock.json')))
    if clocks:   # export once from the ignored run folder so the artifact keeps the numbers
        rows = []
        for f in clocks:
            j = json.loads(Path(f).read_text())
            if j.get('save_tap') and j.get('barrier_utc_ns'):
                rows.append(dict(trial=Path(f).parent.name, save_to_server_s=f"{(j['barrier_utc_ns'] - j['save_tap']['utc_ns']) / 1e9:.3f}"))
        OUT.mkdir(parents=True, exist_ok=True)
        with open(hop2_csv, 'w', encoding='utf-8', newline='') as f:
            wr = csv.DictWriter(f, fieldnames=['trial', 'save_to_server_s'], lineterminator='\n')
            wr.writeheader()
            wr.writerows(rows)
    w['Etar+DAVx5, save to server copy (hop 2)'] = [float(r['save_to_server_s']) for r in read(hop2_csv)]
    return w


def main():
    w = windows()
    OUT.mkdir(parents=True, exist_ok=True)
    wrows = [dict(window=k, n=len(v), min_s=f'{min(v):.2f}', median_s=f'{statistics.median(v):.2f}',
                  max_s=f'{max(v):.2f}') for k, v in w.items()]
    with open(OUT / 'windows.csv', 'w', encoding='utf-8', newline='') as f:
        wr = csv.DictWriter(f, fieldnames=list(wrows[0]), lineterminator='\n')
        wr.writeheader()
        wr.writerows(wrows)
    erows = []
    for k, v in w.items():
        med = statistics.median(v)
        for lam in RATES:
            erows.append(dict(window=k, median_window_s=f'{med:.2f}', interruptions_per_hour=lam,
                              ghost_per_1000_commits=f'{1000 * (1 - math.exp(-lam * med / 3600)):.3f}'))
    with open(OUT / 'estimate.csv', 'w', encoding='utf-8', newline='') as f:
        wr = csv.DictWriter(f, fieldnames=list(erows[0]), lineterminator='\n')
        wr.writeheader()
        wr.writerows(erows)
    lines = ['# How often a ghost window could be hit (FREQ, b-log 21/11): an estimate, not a measurement', '',
             'Generated by `testbed/ghost_window.py`. Windows are measured; interruption and lost-reply rates are an '
             'assumed grid.', '', '| Window | n | min (s) | median (s) | max (s) |', '|---|---|---|---|---|']
    lines += [f"| {r['window']} | {r['n']} | {r['min_s']} | {r['median_s']} | {r['max_s']} |" for r in wrows]
    lines += ['', 'Ghost effects per 1,000 commits if interruptions arrive at rate lam per hour (median window):', '',
              '| Window | ' + ' | '.join(f'lam = {x}/h' for x in RATES) + ' |', '|---|' + '---|' * len(RATES)]
    for k, v in w.items():
        med = statistics.median(v)
        lines.append(f'| {k} | ' + ' | '.join(f'{1000 * (1 - math.exp(-x * med / 3600)):.2f}' for x in RATES) + ' |')
    lines += ['', 'K-9 also turns every lost SMTP reply after commit into a ghost, with no interruption needed: '
              + ', '.join(f'{1000 * p:g} per 1,000 sends at a lost-reply rate of {p:g}' for p in LOST_REPLY) + '.',
              '', 'The hop-2 window of Etar+DAVx5 matters for late commits read from server-backed views; DAVx5 '
              'retries idempotently, so a ghost there is not a duplicate unless an agent redoes the step.']
    (OUT / 'SUMMARY.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    sys.exit(main())
