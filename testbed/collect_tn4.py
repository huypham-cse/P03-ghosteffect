"""TN4 (b-log 22/11): collect the Element held-out run into the artifact.

  python testbed/collect_tn4.py --cal <calibration run dir> [--test <test run dir>] [--out artifact/results/real/tn4_element]

One row per valid trial (INVALID reruns are counted, not listed). Calibration: class, X, commit-to-visible lag, the
two nonce views (timeline row, room-list last message) and server copies. Test: the planner decision, its reason,
certified wait, when the reads finished after the origin, the views it read, and server copies (2+ = duplicate).
Views in calibration X=1 are read after the poll that saw the row, so the timeline view is right by construction
there; the test reads at the certified deadline instead."""
import argparse
import csv
import json
import statistics
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def results(run):
    rs = [json.loads(f.read_text(encoding='utf-8')) for f in sorted(run.glob('[ct][0-9][0-9][0-9][0-9]/RESULT.json'))]
    return rs, sum(1 for d in run.iterdir() if d.is_dir() and 'INVALID' in d.name)


def write(path, rows):
    with open(path, 'w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator='\n')
        w.writeheader()
        w.writerows(rows)


def cal_row(d):
    v = d['views']['nonce']
    return dict(trial=d['name'], x=d['x'], fault_class=d['fault_class'], lag_upper_s=d['lag_upper_seconds'],
                view_timeline=v[0], view_roomlist=v[1], server_copies=len(d['server_copies_final']))


def test_row(d):
    ev = {e['event']: e for e in d['trace']}
    read = ev.get('READ_FAMILY')
    wait = ev.get('CERTIFIED_WAIT')
    v = d['views'] + [None] * (2 - len(d['views']))
    return dict(trial=d['name'], x=d['x'], fault_class=d['fault_class'], decision=d['decision'], reason=d['reason'],
                certified_wait_s=wait and wait['wait'],
                read_after_origin_s=read and wait and round(read['mono_seconds'] - wait['origins'][0], 3),
                view_timeline=v[0], view_roomlist=v[1], server_copies=len(d['server_copies_final']))


def one_sided_zero(n, conf=0.95):
    """One-sided Clopper-Pearson upper bound for 0 events in n."""
    return 1 - (1 - conf) ** (1 / n)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cal', type=Path, required=True)
    p.add_argument('--test', type=Path)
    p.add_argument('--out', type=Path, default=ROOT / 'artifact/results/real/tn4_element')
    a = p.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    cal, cal_bad = results(a.cal)
    crows = [cal_row(d) for d in cal]
    write(a.out / 'calibration.csv', crows)
    lines = ['# TN4: Element held-out run with the real planner (b-log 22/11)', '',
             'Generated by `testbed/collect_tn4.py` from the run directories (outside the repo). AVD x86_64, Element '
             'classic 1.6.62, Synapse 1.164.2 behind the fault proxy; store `testbed/tn4/tn4_store.json`.', '',
             f'## Calibration: {len(crows)} valid trials, {cal_bad} INVALID (rerun)', '',
             '| Class | X=1 | X=0 | Lag median (s) | Lag max (s) | X=1 room list stale | X=0 any view shows it |',
             '|---|---|---|---|---|---|---|']
    for cls in ('none', 'app-kill', 'force-stop'):
        c1 = [r for r in crows if r['fault_class'] == cls and r['x'] == 1]
        c0 = [r for r in crows if r['fault_class'] == cls and r['x'] == 0]
        lags = [r['lag_upper_s'] for r in c1]
        lines.append(f"| {cls} | {len(c1)} | {len(c0)} | {statistics.median(lags):.2f} | {max(lags):.2f} | "
                     f"{sum(r['view_roomlist'] == 0 for r in c1)} | "
                     f"{sum(1 in (r['view_timeline'], r['view_roomlist']) for r in c0)} |")
    if a.test:
        test, test_bad = results(a.test)
        trows = [test_row(d) for d in test]
        write(a.out / 'test.csv', trows)
        lines += ['', f'## Test: {len(trows)} valid trials, {test_bad} INVALID (rerun)', '',
                  '| Class | X | n | COMMITTED | RETRY | ASK | Duplicates (2+ copies) | Lost (0 copies) |',
                  '|---|---|---|---|---|---|---|---|']
        for cls in ('none', 'app-kill', 'force-stop'):
            for x in (1, 0):
                g = [r for r in trows if r['fault_class'] == cls and r['x'] == x]
                k = Counter(r['decision'] for r in g)
                lines.append(f"| {cls} | {x} | {len(g)} | {k['COMMITTED']} | {k['RETRY']} | {k['ASK']} | "
                             f"{sum(r['server_copies'] >= 2 for r in g)} | {sum(r['server_copies'] == 0 for r in g)} |")
        com = [r for r in trows if r['x'] == 1]
        ab = [r for r in trows if r['x'] == 0]
        retried = sum(r['decision'] == 'RETRY' for r in com)
        lines += ['', f'- Committed effects retried: {retried}/{len(com)}' +
                  (f' (one-sided 95% Clopper-Pearson upper bound {100 * one_sided_zero(len(com)):.2f}%).'
                   if com and not retried else '.'),
                  f"- Absent effects retried (certified absence): {sum(r['decision'] == 'RETRY' for r in ab)}/{len(ab)}.",
                  f"- Duplicates on the server: {sum(r['server_copies'] >= 2 for r in trows)}/{len(trows)}."]
    (a.out / 'SUMMARY.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
