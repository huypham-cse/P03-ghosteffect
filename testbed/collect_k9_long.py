"""K9L (b-log 21/11): collect the long-observation K-9 runs (k9_fault_case.py --observe 2100) into the artifact.

  python testbed/collect_k9_long.py [--runs testbed/runs/k9l] [--out artifact/results/real/emu_k9_long]

One row per scheduled trial (INVALID reruns are listed separately): configuration, kill, observation seconds,
server copies, new SMTP DATA after the fault (proxy journal), K-9's Outbox state, and the case's own checks."""
import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--runs', type=Path, default=ROOT / 'testbed/runs/k9l')
    p.add_argument('--out', type=Path, default=ROOT / 'artifact/results/real/emu_k9_long')
    a = p.parse_args()
    rows = []
    for f in sorted(a.runs.glob('l0*/RESULT.json')):
        d = json.loads(f.read_text())
        rows.append(dict(trial=f.parent.name, verdict=d['verdict'], config=d.get('config'), kill=d.get('kill'),
                         observe_s=d.get('observe_s'), server_copies=(d.get('server') or {}).get('copies'),
                         smtp_data_after_fault=d.get('smtp_data_after_fault'), k9_outbox_state=d.get('k9_outbox_state'),
                         all_checks=all((d.get('checks') or {}).values()) if d.get('checks') else None))
    a.out.mkdir(parents=True, exist_ok=True)
    with open(a.out / 'trials.csv', 'w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    valid = [r for r in rows if r['verdict'] == 'REPRODUCED']
    lines = ['# K-9 long observation after a lost SMTP reply (K9L, b-log 21/11)', '',
             'Generated by `testbed/collect_k9_long.py` from `testbed/runs/k9l/` (ignored). AVD x86_64, rig B-04.', '',
             '| Trial | Config | Kill | Observed (s) | Server copies | New DATA after fault | Outbox | Checks |',
             '|---|---|---|---|---|---|---|---|']
    lines += ['| %(trial)s | %(config)s | %(kill)s | %(observe_s)s | %(server_copies)s | %(smtp_data_after_fault)s | '
              '%(k9_outbox_state)s | %(all_checks)s |' % r for r in rows]
    lines += ['', '%d of %d trials reproduced; across them %d new DATA after the fault over %s s each (more than two of '
              "K-9's 15-minute polls)." % (len(valid), len(rows), sum(r['smtp_data_after_fault'] or 0 for r in valid),
                                          valid[0]['observe_s'] if valid else '?')]
    (a.out / 'SUMMARY.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
