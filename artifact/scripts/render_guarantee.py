#!/usr/bin/env python3
"""render_guarantee.py -- part A (guarantee and calibration): CSV -> \\Cert* macros and tab_cert_*.tex.

Reads only CSVs under --results-dir and writes only macros_guarantee.tex and tab_cert_*.tex under --output-dir.
Every output is built in memory first; a missing or malformed input raises before any file is written, so the
previous outputs stay as they were.  Two runs on the same CSVs give byte-identical files (no timestamps, sorted
macros, fixed newline).

Kind of number: every table value is a *measured-parameter simulation* on the Element profile (or the default
model-based world for the bound rows marked "default"), except \\CertElemTrialsN (emulator measurement count),
\\CertLabelMedS (emulator measurement, B's label_cost.csv) and \\CertDelta* (exact computation).

Standalone: python3 artifact/scripts/render_guarantee.py [--results-dir DIR] [--output-dir DIR]
Library:    render(results_dir) -> {file name: text}
Pipeline:   render.py exec()s this file; the last block below then writes through render.py's W().
"""
import argparse
import csv
from decimal import Decimal, ROUND_HALF_UP
import math
import os
from pathlib import Path
import sys

CERT_DIR = Path(__file__).resolve().parent

# Parameters of the runs, not results (CONTRIBUTOR_FIXED YC-04): the risk budgets of every planner run
# (planner_sim.run defaults), the number of observable fault classes (planner_sim.CLASSES) and the per-class
# bound counts K (planner_sim.K_PRODUCT, K_JOINT), and the default lag-table size planner_sim.N_LAG that rows
# without an nlag column (planner_real.csv) use.  test_guarantee.py checks these against planner_sim.
ALPHA_PCT = 1.0
BETA_PCT = 1.0
N_CLASSES = 4
K_PRODUCT, K_JOINT = 11, 5
N_LAG = 20000
OUTCOMES = 2                      # committed and absent labels

POLICIES = (('ghost', 'Prod'), ('ghost-joint', 'Joint'))
CLOCK_ROWS = (('down5', 'DownFive'), ('down15', 'DownFifteen'), ('t0down5', 'TzeroDownFive'),
              ('t0down15', 'TzeroDownFifteen'))
TIED_ROWS = (('lag2k', 'TiedTwo'), ('lag5k', 'TiedFive'))
TAIL_ROWS = (('tail5', 'TailFive'), ('tail5tied', 'TailFiveTied'))
APP_ROWS = (('lag10k', 'TiedTen'), ('lag20k', 'TiedTwenty'), ('boot10k', 'BootTen'))
HEADER = '% AUTO-GENERATED by artifact/scripts/render_guarantee.py -- do not edit by hand\n'


class InputError(Exception):
    """A required CSV, row or column is missing or malformed."""


# ------------------------------------------------------------------ formatting
def num(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return float('nan')
    return v


def cert_half_up(x, d):
    v = num(x)
    if not math.isfinite(v):
        return 'N/A'
    return str(Decimal(repr(v)).quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP))


def cert_f1(x):
    return cert_half_up(x, 1)


def cert_f2(x):
    return cert_half_up(x, 2)


def count(n):
    return f'{int(n):,}'.replace(',', '{,}')


def cert_sci(x):
    e = int(math.floor(math.log10(x)))
    m = x / 10 ** e
    if round(m, 1) >= 10:
        m, e = m / 10, e + 1
    return f'\\ensuremath{{{m:.1f}{{\\times}}10^{{{e}}}}}'


# ------------------------------------------------------------------ inputs
def read_csv(results, name):
    path = Path(results) / name
    if not path.is_file():
        raise InputError(f'missing input CSV: {path}')
    with open(path, newline='', encoding='utf-8-sig') as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise InputError(f'empty input CSV: {path}')
    return rows


def one(rows, what, **match):
    hit = [r for r in rows if all(r.get(k) == v for k, v in match.items())]
    if len(hit) != 1:
        raise InputError(f'{what}: expected exactly one row with {match}, found {len(hit)}')
    return hit[0]


def cert_col(row, name, what):
    if name not in row or row[name] in (None, ''):
        raise InputError(f'{what}: missing column {name}')
    return row[name]


def real4(results, tag):
    rows = read_csv(results, f'planner_real4_{tag}.csv')
    out = {}
    for pol, pn in POLICIES:
        r = one(rows, f'planner_real4_{tag}.csv', policy=pol)
        if r.get('tag') != tag or r.get('app') != 'element':
            raise InputError(f'planner_real4_{tag}.csv: row is not tag {tag} on element')
        out[pn] = r
    return out


# ------------------------------------------------------------------ quantities
def composed_bound(row, side, what):
    """A-04: P(dup | X=1) <= min(1, alpha + q1 eps1 + r1) and P(loss | X=0) <= min(1, beta + q0 eps0 + r0), in %.

    q is the share of effects with that outcome the planner asked about (q1 = ask1/n1), eps the simulated user's
    error rate among those asks (user_e1), r the rate of errors that neither the planner nor the user causes (an
    app that retransmits without dedup, as in section 3), which the simulator assumes is 0.  q*eps is computed from counts, so a zero denominator gives N/A, never 0."""
    n = num(cert_col(row, 'n1' if side == 1 else 'n0', what))
    asked = num(cert_col(row, 'ask1' if side == 1 else 'ask0', what))
    eps = num(row.get('user_e1' if side == 1 else 'user_e0'))
    budget = ALPHA_PCT if side == 1 else BETA_PCT
    if not n > 0:
        return float('nan'), float('nan'), float('nan')
    q = 100 * asked / n
    if asked > 0:
        if not math.isfinite(eps):
            raise InputError(f'{what}: user error rate missing although {asked:.0f} effects were asked')
        term = q * eps / 100
    else:
        eps, term = float('nan'), 0.0          # nobody asked: no user error rate, and no user-caused error
    return q, eps, min(100.0, budget + term)


def delta(k):
    return min(ALPHA_PCT, BETA_PCT) / 100 / (10 * k * N_CLASSES)


def label_median(results):
    """B's measured seconds per fault-injected label (row 'total'); a missing file is an input error (YC-A9)."""
    path = Path(results) / 'real' / 'agent' / 'label_cost.csv'
    rows = read_csv(path.parent, path.name)
    v = num(cert_col(one(rows, 'label_cost.csv', component='total'), 'median_s', 'label_cost.csv'))
    if not v > 0:
        raise InputError('label_cost.csv: total median_s must be positive')
    return v


def label_costs(results):
    """Seconds per label for (committed, absent, all). Prefer TN1's scripted fault-injected label trials on a real app
    (real/tn1_caldav/label_cost.csv, medians per outcome); fall back to B's LLM-agent episode total, which also
    contains the agent's compose time and a 300 s observation window."""
    path = Path(results) / 'real' / 'tn1_caldav' / 'label_cost.csv'
    if not path.exists():
        v = label_median(results)
        return v, v, v
    rows = read_csv(path.parent, path.name)
    med = lambda c: num(cert_col(one(rows, 'label_cost.csv', component=c), 'median_s', 'label_cost.csv'))
    out = med('committed'), med('absent'), med('total')
    if not all(v > 0 for v in out):
        raise InputError('tn1 label_cost.csv: median_s must be positive')
    return out


# ------------------------------------------------------------------ tables
DAGGER = '$^\\dagger$'


def pv_cell(r):
    mark = DAGGER if num(r['cdup_hi']) > ALPHA_PCT else ''
    return f"{cert_f2(r['cdup'])} ({cert_f2(r['cdup_hi'])}){mark} & {cert_f1(r['ask'])}"


def clock_row(tag, rows):
    anchor = '$r_e$' if tag.startswith('down') else '$t_0$'
    down = '%g' % num(rows['Prod']['downtime'])
    return f"{anchor}, {down}" + '\\,s & ' + f"{pv_cell(rows['Prod'])} & {pv_cell(rows['Joint'])}" + ' \\\\'


def table(label, caption, head, body, cols='@{}l cc cc@{}'):
    return (f'\\begin{{table}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\scriptsize\n'
            f'\\setlength{{\\tabcolsep}}{{3pt}}\n\\begin{{tabular}}{{{cols}}}\n\\toprule\n{head}\n\\midrule\n'
            + '\n'.join(body) + '\n\\bottomrule\n\\end{tabular}\n\\end{table}\n')


POL_HEAD = (' & \\multicolumn{2}{c}{product} & \\multicolumn{2}{c}{joint} \\\\\n'
            '\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n'
            '%s & $P_{\\mathrm v}$ (CP) & ask & $P_{\\mathrm v}$ (CP) & ask \\\\')
PV_NOTE = ('$P_{\\mathrm v}$: \\% of committed effects the planner retried by itself, with the upper end of its '
           'two-sided 95\\% Clopper-Pearson interval (CP). Ask: \\% of workflows. Budget $\\alpha=' + f'{ALPHA_PCT:g}'
           + '\\%$. $^\\dagger$: CP bound over budget.')


def budget_label(r, nlag, extra=''):
    labels = count(int(num(r['ncal'])))
    tied = ' (tied)' if nlag == labels else ''
    return f'{labels} / {nlag}{tied}{extra}'


def render(results):
    """Return {file name: text}.  Raises InputError before anything is written."""
    results = Path(results)
    M = {}
    real = read_csv(results, 'planner_real.csv')
    main = {pn: one(real, 'planner_real.csv', tag='main', app='element', policy=pol) for pol, pn in POLICIES}
    five = {pn: one(real, 'planner_real.csv', tag='five', app='element', policy=pol) for pol, pn in POLICIES}
    sim = read_csv(results, 'planner_sim.csv')
    default = {pn: one(sim, 'planner_sim.csv', policy=pol) for pol, pn in POLICIES}
    R4 = {tag: real4(results, tag) for tag, _ in CLOCK_ROWS + TIED_ROWS + TAIL_ROWS + APP_ROWS}

    def put(prefix, rows, cols=('Pv', 'PvHi', 'Ask')):
        for pn, r in rows.items():
            for c in cols:
                M[prefix + pn + c] = {'Pv': lambda: cert_f2(r['cdup']), 'PvHi': lambda: cert_f2(r['cdup_hi']),
                                      'Ask': lambda: cert_f1(r['ask']),
                                      'Over': lambda: 'over budget' if num(r['cdup_hi']) > ALPHA_PCT
                                      else 'within budget'}[c]()

    for tag, name in CLOCK_ROWS:
        put('CertClock' + name, R4[tag])
    for tag, name in TIED_ROWS + APP_ROWS:
        put('Cert' + name, R4[tag])
    for tag, name in TAIL_ROWS:
        put('Cert' + name, R4[tag], ('Pv', 'PvHi', 'Ask', 'Over'))

    # A-02 label accounting
    params = read_csv(results / 'real', 'params.csv')
    lag_cells = [r for r in params if r.get('name', '').startswith('elem_lag_')]
    if not lag_cells:
        raise InputError('params.csv: no elem_lag_* rows')
    M['CertElemTrialsN'] = count(sum(len(r['value'].split('|')) for r in lag_cells))
    base, labels5 = int(num(main['Prod']['ncal'])), int(num(R4['lag5k']['Prod']['ncal']))
    if base <= 0 or labels5 <= 0:
        raise InputError('ncal must be positive')
    M['CertLabelsBase'] = count(base)
    M['CertLabelsFive'] = count(labels5)
    M['CertPilotFive'] = count(labels5 // 10)
    M['CertHoldoutFive'] = count(labels5 - labels5 // 10)
    for tag in ('down5', 'tail5'):          # bootstrap-lag rows must record the default size
        if int(num(R4[tag]['Prod']['nlag'])) != N_LAG:
            raise InputError(f'planner_real4_{tag}.csv: nlag differs from N_LAG={N_LAG}')
    M['CertLagBootN'] = count(N_LAG)
    M['CertClassesN'] = str(N_CLASSES)

    # A-04 composed bounds
    bounds = {}
    for world, rows in (('Elem', main), ('Def', default)):
        for pn, r in rows.items():
            what = f'{world} {pn}'
            q1, e1, dup = composed_bound(r, 1, what)
            q0, e0, loss = composed_bound(r, 0, what)
            bounds[(world, pn)] = (q1, e1, dup, q0, e0, loss)
            pre = 'CertBound' + world + pn
            M[pre + 'Qone'], M[pre + 'EpsOne'], M[pre + 'Dup'] = cert_f2(q1), cert_f2(e1), cert_f2(dup)
            M[pre + 'Qzero'], M[pre + 'EpsZero'], M[pre + 'Loss'] = cert_f2(q0), cert_f2(e0), cert_f2(loss)

    # A-05 exact computation
    M['CertDeltaProd'] = cert_sci(delta(K_PRODUCT))
    M['CertDeltaJoint'] = cert_sci(delta(K_JOINT))

    # A-08: B's measured label time
    med1, med0, med = label_costs(results)
    M['CertLabelMedS'] = f'{med:.0f}'
    M['CertLabelMedOneS'] = f'{med1:.0f}'
    M['CertLabelMedZeroS'] = f'{med0:.0f}'
    assert OUTCOMES == 2
    M['CertDeviceHoursFive'] = count(round(labels5 * N_CLASSES * (med1 + med0) / 3600))

    files = {'macros_guarantee.tex': HEADER + ''.join(
        f'\\newcommand{{\\{k}}}{{{v}\\xspace}}\n' for k, v in sorted(M.items()))}

    lagn = lambda r: count(int(num(r['nlag'])))
    files['tab_cert_clock.tex'] = HEADER + table(
        'tab:cert-clock',
        '\\emph{Measured-parameter simulation}, Element, '
        f"{count(int(num(R4['down5']['Prod']['n'])))} interrupted workflows per row, "
        f"{count(int(num(R4['down5']['Prod']['ncal'])))} labels per class and outcome. "
        'The app or network is down for 5 or 15\\,s before the anchor $r_e$. '
        'Rows wait from the anchor $r_e$ of \\S\\ref{sec:model} or from $t_0$ for every class. '
        + PV_NOTE,
        POL_HEAD % 'wait from, downtime',
        [clock_row(tag, R4[tag]) for tag, _ in CLOCK_ROWS])

    budget_rows = [('main', main, ''), ('lag2k', R4['lag2k'], ''), ('five', five, ''), ('lag5k', R4['lag5k'], ''),
                   ('tail5', R4['tail5'], 'tail'), ('tail5tied', R4['tail5tied'], 'tail')]
    body = []
    for tag, rows, tail in budget_rows:
        r = rows['Prod']
        nlag = lagn(r) if r.get('nlag') not in (None, '') else count(N_LAG)
        body.append(budget_label(r, nlag, ', tail' if tail else '') + ' & '
                    + f"{pv_cell(rows['Prod'])} & {pv_cell(rows['Joint'])}" + ' \\\\')
    tail_pct = cert_f1(100 * num(R4['tail5']['Prod']['lag_tail']))
    files['tab_cert_budget.tex'] = HEADER + table(
        'tab:cert-budget',
        '\\emph{Measured-parameter simulation}, Element: label budget. '
        "Rows give labels per class and outcome / lag entries per class. ``Tied'' rows draw as many lag entries "
        f"as labels. ``Tail'': a {tail_pct}\\% share of committed effects (the one-sided 95\\% upper bound from zero "
        'censored emulator trials) becomes visible only after the logged lags, and the calibration labels do not '
        'see it. ' + PV_NOTE,
        POL_HEAD % 'labels / lag entries', body)

    files['tab_cert_lagapp.tex'] = HEADER + table(
        'tab:cert-lagapp',
        '\\emph{Measured-parameter simulation}, Element: larger label budgets. '
        "Rows give labels per class and outcome / lag entries per class. ``Tied'' rows draw as many lag entries as "
        "labels. ``Bootstrap'': lag entries resampled from the measured lags. " + PV_NOTE,
        POL_HEAD % 'labels / lag entries',
        [budget_label(R4[tag]['Prod'], lagn(R4[tag]['Prod']), ', bootstrap' if tag.startswith('boot') else '')
         + ' & ' + f"{pv_cell(R4[tag]['Prod'])} & {pv_cell(R4[tag]['Joint'])}" + ' \\\\' for tag, _ in APP_ROWS])

    files['tab_cert_bound.tex'] = HEADER + table(
        'tab:cert-bound',
        'Composed error bounds. $P(\\mathrm{dup}\\mid X{=}1)\\le\\min(1,\\alpha+q_1\\epsilon_1+r_1)$ and '
        '$P(\\mathrm{loss}\\mid X{=}0)\\le\\min(1,\\beta+q_0\\epsilon_0+r_0)$, with $r_1=r_0=0$ assumed by the simulator. '
        '$q_x$: \\% of effects with outcome $x$ the planner asks about; $\\epsilon_x$: \\% of those answers the simulated '
        'user gets wrong. Element: \\emph{measured-parameter simulation}; default: \\emph{model-based simulation}. '
        f'Budgets $\\alpha=\\beta={ALPHA_PCT:g}\\%$. N/A: no effect in the denominator.',
        ' & $q_1$ & $\\epsilon_1$ & dup bound & $q_0$ & $\\epsilon_0$ & loss bound \\\\',
        [f"{'Element' if w == 'Elem' else 'default'}, {'product' if pn == 'Prod' else 'joint'} & "
         + ' & '.join(cert_f2(v) for v in bounds[(w, pn)]) + ' \\\\'
         for w in ('Elem', 'Def') for pn in ('Prod', 'Joint')],
        cols='@{}l ccc ccc@{}')
    return files


def publish(files, output):
    """Write every file next to its target first, then rename, so a failure leaves complete old or new files."""
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    temps = []
    try:
        for name, text in sorted(files.items()):
            tmp = output / f'.{name}.tmp'
            with open(tmp, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            temps.append((tmp, output / name))
        for tmp, dst in temps:
            os.replace(tmp, dst)
    finally:
        for tmp, _ in temps:
            if tmp.exists():
                tmp.unlink()


def cert_main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results-dir', type=Path, default=CERT_DIR.parent / 'results')
    parser.add_argument('--output-dir', type=Path, default=CERT_DIR.parent.parent / 'manuscript' / 'generated')
    args = parser.parse_args(argv)
    try:
        files = render(args.results_dir)
    except InputError as e:
        print(f'render_guarantee: {e}', file=sys.stderr)
        return 1
    publish(files, args.output_dir)
    n = files['macros_guarantee.tex'].count('\\newcommand')
    print(f'render_guarantee: wrote {n} macros and {len(files) - 1} tables to {args.output_dir}')
    return 0


if 'W' in globals() and 'RES' in globals() and 'MACROS' in globals():
    # Executed by render.py (C-01 wiring: exec of this file in render.py's namespace, after its own outputs).
    # Write through render.py's W into its staging directory.  An InputError aborts the whole render, so the
    # published generated/ directory stays as it was.  Module-level names here avoid render.py's (cert_*).
    for _cert_name, _cert_text in sorted(render(RES).items()):
        W(_cert_name, _cert_text)
elif __name__ == '__main__':
    raise SystemExit(cert_main())
